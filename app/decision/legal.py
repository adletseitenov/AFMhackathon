def legal_basis(category, licensed: bool = False, text=None) -> dict:
    """Правовое основание кейса: статьи РК + наказание + ЗАКОННЫЙ путь мер.

    category — 'gambling' | 'pyramid' | 'fraud' | 'clean'/иное.
    licensed — True, если в кейсе лицензированный в РК оператор (для gambling
               отдаём «рекламный» режим без уголовных статей).
    Возвращает {category, category_ru, articles:[{code,article,title,summary,
    punishment}], enforcement:[str], disclaimer}. Никогда не бросает.
    """
    cat = (category if isinstance(category, str) else "").strip().lower()

    # Лицензированный гемблинг — отдельная, «рекламная» ветка (не уголовная).
    if cat == "gambling" and licensed:
        spec = _LEGAL_GAMBLING_LICENSED
        return {
            "category": cat,
            "category_ru": spec["category_ru"],
            "articles": [dict(a) for a in spec["articles"]],
            "enforcement": list(spec["enforcement"]),
            "disclaimer": LEGAL_DISCLAIMER,
        }

    spec = _LEGAL_BY_CATEGORY.get(cat)
    if spec is None:
        # Неизвестная/чистая категория — без обвинительных статей, только проверка.
        return {
            "category": cat,
            "category_ru": "не классифицировано как угроза",
            "articles": [],
            "enforcement": [
                "Признаков состава нет — основания для мер реагирования "
                "отсутствуют; оставить под наблюдением, пересмотреть при новых "
                "сигналах.",
            ],
            "disclaimer": LEGAL_DISCLAIMER,
        }

    enforcement = list(spec.get("enforcement", [])) + list(_ENFORCEMENT_COMMON)
    return {
        "category": cat,
        "category_ru": spec["category_ru"],
        "articles": [dict(a) for a in spec["articles"]],
        "enforcement": enforcement,
        "disclaimer": LEGAL_DISCLAIMER,
    }
