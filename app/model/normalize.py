"""F3 (антифрод) — нормализация обфусцированного текста для матчинга сигналов.

Скам-объявления обходят словарные/regex-детекторы тремя приёмами:
  1) РАЗРЯДКА букв пробелами/точками — «к а з и н о», «1 x b e t», «к.а.з.и.н.о»;
  2) ГОМОГЛИФЫ — латиница вместо кириллицы (и наоборот): «kаzино», «1xБ3т»;
  3) ЛИТСПИК — цифры вместо букв внутри слова: «1xб3т» (3->е/з, 1->и, 0->о…);
  плюс невидимые/нулевой-ширины символы между буквами.

`normalize_obfuscated(text)` возвращает НОРМАЛИЗОВАННУЮ КОПИЮ строки для матчинга
(её скармливают в regex сигналов и в TF-IDF), НЕ разрушая исходный отображаемый текст.

Гарантии:
  • idempotent: normalize_obfuscated(normalize_obfuscated(x)) == normalize_obfuscated(x);
  • никогда не падает на None/пустом/нестроковом входе (возвращает "");
  • lowercases для матчинга;
  • TORCH-FREE: чистый Python + re, без внешних зависимостей.

Подключается в app.model.features.build_features (матчинг сигналов идёт по
нормализованному combined_text) и в train/inference текстового TF-IDF — так что
'1 x b e t', 'kаzино', '1xб3т' срабатывают на тех же сигналах, что и канон.
"""

from __future__ import annotations

import re
import unicodedata

# --- Невидимые символы / нулевой ширины (вырезаем полностью) ---
# ZWSP, ZWNJ, ZWJ, BOM/ZWNBSP, soft-hyphen, LRM/RLM, word-joiner.
_ZERO_WIDTH = dict.fromkeys(
    [
        0x00AD,  # SOFT HYPHEN
        0x200B,  # ZERO WIDTH SPACE
        0x200C,  # ZERO WIDTH NON-JOINER
        0x200D,  # ZERO WIDTH JOINER
        0x200E,  # LEFT-TO-RIGHT MARK
        0x200F,  # RIGHT-TO-LEFT MARK
        0x2060,  # WORD JOINER
        0xFEFF,  # ZERO WIDTH NO-BREAK SPACE / BOM
    ],
    None,
)

# --- Гомоглифы: латиница -> кириллица (приводим визуальные двойники к кириллице).
# Скамеры пишут «kаzино» (k/z латиницей, остальное кириллицей) чтобы обойти словарь.
# Маппим только однозначные визуальные двойники; уже в нижнем регистре.
#
# ВАЖНО (поправка после регрессии): фолдим ТОЛЬКО в ТОКЕНАХ СО СМЕШАННЫМ СКРИПТОМ
# (латиница И кириллица в одном слове) — это и есть подпись атаки «kаzино». ЧИСТО
# латинские слова (casino, melbet, 1xbet, pin-up, mostbet, parimatch) НЕ трогаем:
# иначе мы бы калечили легитимные латинские бренды в кириллицу (melbet->меlвет) и
# ломали Latin-литералы в regex-сигналах (casino_betting_brand). См. _homoglyph_fold.
_LAT_TO_CYR = {
    "a": "а",
    "b": "в",  # визуальный двойник кириллической В (в нижнем регистре спорно, но в скаме частый)
    "c": "с",
    "e": "е",
    "h": "н",
    "k": "к",
    "m": "м",
    "o": "о",
    "p": "р",
    "t": "т",
    "x": "х",
    "y": "у",
    "z": "з",  # не двойник, но в «kаzино» z подменяет з — частый приём
}

# --- Литспик: цифры, используемые как буквы ВНУТРИ алфавитного контекста.
# Применяем КОНСЕРВАТИВНО — только если цифра окружена буквами (см. _deleet),
# чтобы не калечить суммы/проценты/телефоны.
_LEET_TO_CHAR = {
    "0": "о",
    "1": "и",
    "3": "е",
    "4": "ч",
    "5": "ъ",  # редко; оставим, но почти не встретится в алфавит-контексте
    "6": "б",
    "8": "в",
}

# Буква (кириллица или латиница) — для определения «алфавитного контекста».
_ALPHA = "[a-zA-Zа-яёА-ЯЁәғқңөұүһіӘҒҚҢӨҰҮҺІ]"
# Одиночный «токен» при разрядке: одна буква/цифра, окружённая разделителями.

# Наборы букв для определения скрипта токена (нижний регистр).
_LAT_LETTERS = set("abcdefghijklmnopqrstuvwxyz")
_CYR_LETTERS = set("абвгдеёжзийклмнопрстуфхцчшщъыьэюяәғқңөұүһі")
# Прогон букв (любой скрипт) — единица, на которой решаем, фолдить или нет.
_LETTER_RUN = re.compile(r"[a-zA-Zа-яёА-ЯЁәғқңөұүһіӘҒҚҢӨҰҮҺІ]+")


def _strip_zero_width(text: str) -> str:
    return text.translate(_ZERO_WIDTH)


def _homoglyph_fold(text: str) -> str:
    """Латинские визуальные двойники -> кириллица ТОЛЬКО в смешанно-скриптовых словах.

    Подпись атаки — слово, где латиница и кириллица перемешаны в ОДНОМ токене
    («kаzино», «1xб3т» после делита): такой токен сворачиваем в кириллицу. Чисто
    латинские слова (casino, melbet, 1xbet, pin-up) оставляем как есть — это
    легитимные бренды, и их ловят Latin-литералы в regex-сигналах. Текст уже lower.
    """
    def _fold_tok(m: "re.Match") -> str:
        tok = m.group(0)
        has_lat = any(c in _LAT_LETTERS for c in tok)
        has_cyr = any(c in _CYR_LETTERS for c in tok)
        if has_lat and has_cyr:
            return "".join(_LAT_TO_CYR.get(c, c) for c in tok)
        return tok

    return _LETTER_RUN.sub(_fold_tok, text)


def _collapse_spaced_letters(text: str) -> str:
    """Склеивает «к а з и н о» / «1 x b e t» / «к.а.з.и.н.о» в «казино»/«1xbet».

    Идея: последовательность из >=2 одиночных алфанумерик-токенов, разделённых
    одиночными пробелами/точками/дефисами, склеивается без разделителя. Обычные
    слова (длиной >1) и нормальные пробелы между словами не трогаем.
    """
    # Токен = ровно один алфанумерик-символ. Разделитель = пробел/точка/дефис/таб.
    # Находим прогоны вида: c (sep c){1,} и склеиваем буквы.
    pattern = re.compile(
        r"(?<![^\s.\-])"            # перед прогоном — начало строки или разделитель
        r"([0-9a-zA-Zа-яёА-ЯЁәғқңөұүһіӘҒҚҢӨҰҮҺІ])"  # первая одиночная буква/цифра
        r"((?:[\s.\-]+[0-9a-zA-Zа-яёА-ЯЁәғқңөұүһіӘҒҚҢӨҰҮҺІ]){1,})"  # ' x'(' e')...
        r"(?![^\s.\-])"            # после прогона — конец или разделитель
    )

    def _join(m: "re.Match") -> str:
        first = m.group(1)
        rest = re.sub(r"[\s.\-]+", "", m.group(2))
        return first + rest

    return pattern.sub(_join, text)


def _deleet(text: str) -> str:
    """Заменяет цифры на буквы ТОЛЬКО внутри алфавитного контекста (буква_цифра_буква
    или буква на одной из границ), чтобы не трогать суммы/проценты/коды.

    '1xб3т' -> сначала '1' имеет справа букву 'x'(->х) => '1'->'и'? Нет: '1' в начале
    бренда «1xbet» — намеренно сохраняем КАК ОТДЕЛЬНЫЙ срабатыватель букмекера, но
    внутрисловная '3' в 'б3т' -> 'е'. Поэтому правило: цифра конвертится, если ХОТЯ БЫ
    с одной стороны вплотную стоит кириллическая/латинская буква И это не «ведущая
    цифра бренда» (1x..., 1в...). Достаточно консервативно для скам-слов.
    """
    if not any(d in text for d in _LEET_TO_CHAR):
        return text
    chars = list(text)
    n = len(chars)

    def is_alpha(i: int) -> bool:
        return 0 <= i < n and bool(re.match(_ALPHA, chars[i]))

    for i, ch in enumerate(chars):
        if ch not in _LEET_TO_CHAR:
            continue
        left_alpha = is_alpha(i - 1)
        right_alpha = is_alpha(i + 1)
        # Конвертируем, только если цифра реально стоит ВНУТРИ слова между букв или
        # примыкает к букве слева (б3т, сл0т) — но НЕ если это ведущая цифра «1x»/«1в»
        # бренда (там левой буквы нет, а справа буква — оставляем цифру как часть бренда).
        if left_alpha and (right_alpha or not right_alpha):
            chars[i] = _LEET_TO_CHAR[ch]
    return "".join(chars)


def normalize_obfuscated(text) -> str:
    """Нормализованная КОПИЯ текста для матчинга сигналов (см. модульный docstring).

    Шаги (порядок важен):
      0) None/нестрока -> "";
      1) Unicode NFKC (схлопывает совместимые формы) + удаление нулевой-ширины;
      2) lowercase;
      3) склейка разрядки «к а з и н о» -> «казино»;
      4) литспик внутри слов (б3т -> бет), консервативно;
      5) гомоглифы латиница -> кириллица (kаzино -> казино);
      6) схлопывание повторных пробелов.

    Idempotent и crash-safe.
    """
    if not text or not isinstance(text, str):
        return ""
    try:
        t = unicodedata.normalize("NFKC", text)
        t = _strip_zero_width(t)
        t = t.lower()
        t = _collapse_spaced_letters(t)
        t = _deleet(t)
        t = _homoglyph_fold(t)
        t = re.sub(r"\s+", " ", t).strip()
        return t
    except Exception:
        # Никогда не роняем пайплайн извлечения признаков из-за странного ввода.
        try:
            return str(text).lower()
        except Exception:
            return ""


def preview(text, limit: int = 160) -> str:
    """Короткий предпросмотр нормализованного текста для UI/объяснения (crash-safe)."""
    norm = normalize_obfuscated(text)
    if len(norm) > limit:
        return norm[: limit - 1].rstrip() + "…"
    return norm
