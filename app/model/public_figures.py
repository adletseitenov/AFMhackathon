_ALIAS_INDEX.sort(key=lambda t: len(t[0]), reverse=True)


def match(text) -> list[str]:
    """Возвращает список канонических имён публичных фигур, упомянутых в тексте.

    Матчинг по НОРМАЛИЗОВАННОМУ тексту (collapses разрядку, гомоглифы, литспик),
    подстрокой по границам — но мы храним достаточно длинные алиасы (фамилии/ФИО),
    чтобы не ловить шум. Дедуп по каноническому имени, порядок — по первому вхождению.
    Crash-safe: на пустом/None входе -> [].
    """
    norm = normalize_obfuscated(text)
    if not norm:
        return []
    found: list[str] = []
    seen: set[str] = set()
    for alias_norm, canonical, _role in _ALIAS_INDEX:
        if canonical in seen:
            continue
        if alias_norm and alias_norm in norm:
            seen.add(canonical)
            found.append(canonical)
    return found


def matches(text) -> bool:
    """True, если в тексте упомянута хотя бы одна публичная фигура (crash-safe)."""
    return bool(match(text))
