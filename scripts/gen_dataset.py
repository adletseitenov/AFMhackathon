def _fill(tpl: str) -> str:
    return tpl.format(
        brand=random.choice(BRANDS),
        code=random.choice(CODES),
        amount=random.choice(AMOUNTS),
        pct=random.choice(PCTS),
        wallet=random.choice(WALLETS),
        handle=random.choice(HANDLES),
        city=random.choice(CITIES),
    )


def _expand(templates, lang, label, n):
    """Раскрывает шаблоны в n уникальных строк через многократное заполнение слотов."""
    rows, seen = [], set()
    attempts = 0
    while len(rows) < n and attempts < n * 60:
        attempts += 1
        text = _fill(random.choice(templates))
        if text not in seen:
            seen.add(text)
            rows.append({"text": text, "lang": lang, "label": label})
    return rows


def _expand_boundary(templates, lang, label_a, label_b, n, frac_a=0.55):
    """Граничная коллизия: n уникальных текстов из ОБЩИХ шаблонов, ярлык назначается
    стохастически между двумя соседними классами (frac_a -> label_a, иначе label_b).

    Один и тот же поверхностный текст может встретиться под обоими ярлыками, что
    моделирует разногласие разметчиков на границе и гарантирует небольшую
    неустранимую off-diagonal путаницу (датасет перестаёт быть тривиально-
    разделимым). Признаки/модель НЕ затрагиваются."""
    rows, seen = [], set()
    attempts = 0
    while len(rows) < n and attempts < n * 60:
        attempts += 1
        text = _fill(random.choice(templates))
        if text in seen:
            continue
        seen.add(text)
        label = label_a if random.random() < frac_a else label_b
        rows.append({"text": text, "lang": lang, "label": label})
    return rows


def build_rows():
    rows = []

    # --- ЯДРОВЫЕ однозначные (сильный сигнал) ---
    rows += _expand(GAMBLING_RU, "ru", "gambling", 120)
    rows += _expand(GAMBLING_KZ, "kk", "gambling", 45)
    rows += _expand(PYRAMID_RU, "ru", "pyramid", 120)
    rows += _expand(PYRAMID_KZ, "kk", "pyramid", 45)
    rows += _expand(FRAUD_RU, "ru", "fraud", 120)
    rows += _expand(FRAUD_KZ, "kk", "fraud", 45)
    rows += _expand(CLEAN_RU, "ru", "clean", 120)
    rows += _expand(CLEAN_KZ, "kk", "clean", 45)

    # --- (a) пограничные / неоднозначные (БОЛЬШАЯ доля — это источник off-diagonal ошибок) ---
    # clean-«инвестор» / clean-«спорт» / clean-«акция» / clean-«короткая болтовня» — трудные негативы
    rows += _expand(AMBIG_CLEAN_INVEST_RU, "ru", "clean", 40)
    rows += _expand(AMBIG_CLEAN_SPORT_RU, "ru", "clean", 36)
    rows += _expand(AMBIG_CLEAN_PROMO_RU, "ru", "clean", 24)
    rows += _expand(AMBIG_CLEAN_SHORT_RU, "ru", "clean", 24)
    # мягкие версии рискованных классов (слабый/смешанный сигнал, пересекается с соседями)
    rows += _expand(AMBIG_PYRAMID_SOFT_RU, "ru", "pyramid", 44)
    rows += _expand(AMBIG_GAMBLING_SOFT_RU, "ru", "gambling", 36)
    rows += _expand(AMBIG_FRAUD_SOFT_RU, "ru", "fraud", 36)

    # --- (b) короткие / малосигнальные ---
    rows += _expand(SHORT_GAMBLING_RU, "ru", "gambling", 16)
    rows += _expand(SHORT_PYRAMID_RU, "ru", "pyramid", 16)
    rows += _expand(SHORT_FRAUD_RU, "ru", "fraud", 16)

    # --- (c) граничные коллизии (общий текст -> два соседних ярлыка) ---
    # Это главный источник правдоподобной off-diagonal путаницы в held-out.
    rows += _expand_boundary(
        BOUNDARY_PYRAMID_CLEAN_RU, "ru", "pyramid", "clean", 40, frac_a=0.55
    )
    rows += _expand_boundary(
        BOUNDARY_GAMBLING_FRAUD_RU, "ru", "gambling", "fraud", 40, frac_a=0.55
    )
    rows += _expand_boundary(
        BOUNDARY_GAMBLING_CLEAN_RU, "ru", "gambling", "clean", 32, frac_a=0.6
    )

    random.shuffle(rows)
    return rows


