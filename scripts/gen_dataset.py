def _expand(templates, lang, label, n):
    """Раскрывает шаблоны в n уникальных строк через многократное заполнение слотов."""
    rows, seen = [], set()
    attempts = 0
    while len(rows) < n and attempts < n * 60:
        attempts += 1
        text = _fill(random.choice(templates))
        if text not in seen:
            seen.add(text)
            rows.append({"text": text, "lang": lang, "label": label})
    return rows


def _expand_boundary(templates, lang, label_a, label_b, n, frac_a=0.55):
    """Граничная коллизия: n уникальных текстов из ОБЩИХ шаблонов, ярлык назначается
    стохастически между двумя соседними классами (frac_a -> label_a, иначе label_b).

    Один и тот же поверхностный текст может встретиться под обоими ярлыками, что
    моделирует разногласие разметчиков на границе и гарантирует небольшую
    неустранимую off-diagonal путаницу (датасет перестаёт быть тривиально-
    разделимым). Признаки/модель НЕ затрагиваются."""
    rows, seen = [], set()
    attempts = 0
    while len(rows) < n and attempts < n * 60:
        attempts += 1
        text = _fill(random.choice(templates))
        if text in seen:
            continue
        seen.add(text)
        label = label_a if random.random() < frac_a else label_b
        rows.append({"text": text, "lang": lang, "label": label})
    return rows


