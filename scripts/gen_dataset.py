def _fill(tpl: str) -> str:
    return tpl.format(
        brand=random.choice(BRANDS),
        code=random.choice(CODES),
        amount=random.choice(AMOUNTS),
        pct=random.choice(PCTS),
        wallet=random.choice(WALLETS),
        handle=random.choice(HANDLES),
        city=random.choice(CITIES),
    )


def _expand(templates, lang, label, n):
    """Раскрывает шаблоны в n уникальных строк через многократное заполнение слотов."""
    rows, seen = [], set()
    attempts = 0
    while len(rows) < n and attempts < n * 40:
        attempts += 1
        text = _fill(random.choice(templates))
        if text not in seen:
            seen.add(text)
            rows.append({"text": text, "lang": lang, "label": label})
    return rows


def build_rows():
    rows = []
    # gambling
    rows += _expand(GAMBLING_RU, "ru", "gambling", 95)
    rows += _expand(GAMBLING_KZ, "kk", "gambling", 35)
    # pyramid
    rows += _expand(PYRAMID_RU, "ru", "pyramid", 95)
    rows += _expand(PYRAMID_KZ, "kk", "pyramid", 35)
    # fraud
    rows += _expand(FRAUD_RU, "ru", "fraud", 95)
    rows += _expand(FRAUD_KZ, "kk", "fraud", 35)
    # clean (трудные негативы)
    rows += _expand(CLEAN_RU, "ru", "clean", 95)
    rows += _expand(CLEAN_KZ, "kk", "clean", 35)
    random.shuffle(rows)
    return rows


def main():
    rows = build_rows()
    DATASET_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(DATASET_PATH, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    # ASCII-safe вывод: путь может содержать не-cp1252 символы (напр. «Документы»).
    msg = f"Wrote {len(rows)} rows to {DATASET_PATH}"
    print(msg.encode("ascii", "replace").decode("ascii"))


if __name__ == "__main__":
    main()
